"""Regenerate the Page Header JSON-LD for the eleven territory pages.

Each header keeps its own WebPage (name, description) and BreadcrumbList
(crumb name) from the header already in the repo, and carries a FAQPage that
mirrors the page's on-page FAQ verbatim, tags stripped, in page order.
LocalBusiness is referenced by @id from the site-wide header, never redefined.
The pricing answer is asserted byte-identical across every page generated.

    python3 tools/mkterritory.py
"""
import sys, json, re, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import faq

BASE = "https://www.omnifittraining.com"
TERRITORIES = ["4s-ranch", "carlsbad", "carmel-valley", "del-mar", "encinitas", "fairbanks-ranch",
               "la-jolla", "rancho-bernardo", "rancho-santa-fe", "santaluz", "solana-beach"]
LD = re.compile(r'<script type="application/ld\+json">\s*(.*?)\s*</script>', re.S)


def strip_tags(text):
    """faq._clean() turns every tag into a space, which leaves 'page .' where
    the page had 'page</a>.'. Pull the space back in before punctuation."""
    text = re.sub(r'\s+([.,:;!?)])', r'\1', text)
    return re.sub(r'\(\s+', '(', text)


def existing(slug):
    path = f'pages/headers/{slug}-header.html'
    nodes = []
    for b in LD.findall(open(path).read()):
        d = json.loads(b)
        nodes += d.get('@graph', [d]) if isinstance(d, dict) else d
    web = next(n for n in nodes if n.get('@type') == 'WebPage')
    crumbs = next(n for n in nodes if n.get('@type') == 'BreadcrumbList')
    return web['name'], web['description'], crumbs['itemListElement'][-1]['name']


def build(slug):
    page = open(f'pages/{slug}.html').read()
    title, desc, crumb = existing(slug)
    pairs = [(strip_tags(q), strip_tags(a)) for q, a in faq.qa_strict(page)]
    graph = [
        {"@type": "WebPage", "@id": f"{BASE}/{slug}#webpage", "url": f"{BASE}/{slug}",
         "name": title, "description": desc,
         "about": {"@id": f"{BASE}/#localbusiness-of"},
         "breadcrumb": {"@id": f"{BASE}/{slug}#breadcrumb"}, "inLanguage": "en-US"},
        {"@type": "BreadcrumbList", "@id": f"{BASE}/{slug}#breadcrumb", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home", "item": f"{BASE}/"},
            {"@type": "ListItem", "position": 2, "name": crumb, "item": f"{BASE}/{slug}"}]},
        {"@type": "FAQPage", "@id": f"{BASE}/{slug}#faq",
         "mainEntity": [{"@type": "Question", "name": q,
                         "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in pairs]},
    ]
    doc = {"@context": "https://schema.org", "@graph": graph}
    label = slug.replace('personal-trainer-', '').replace('-', ' ').upper()
    note = (f"<!-- {label} PAGE HEADER JSON-LD · v3 OCTOBER 2026\n"
            f"  Header file: pages/headers/{slug}-header.html (written by\n"
            f"  tools/mkterritory.py; build.py injects it into /{slug}).\n\n"
            f"  Generated by tools/mkterritory.py. FAQPage mirrors the on-page FAQ\n"
            f"  verbatim (tags stripped), in page order. LocalBusiness is referenced by\n"
            f"  @id from the site-wide header, never redefined here. Pricing answer is\n"
            f"  byte-identical across all eleven territory pages (October 2026 card).\n-->\n")
    out = note + '<script type="application/ld+json">\n' + json.dumps(doc, indent=2, ensure_ascii=False) + '\n</script>\n'
    open(f'pages/headers/{slug}-header.html', 'w').write(out)
    price = next(a for q, a in pairs if 'cost' in q.lower() and 'personal train' in q.lower())
    return len(pairs), price


if __name__ == "__main__":
    prices = {}
    for t in TERRITORIES:
        slug = f'personal-trainer-{t}'
        n, price = build(slug)
        prices[slug] = price
        print(f"  pages/headers/{slug}-header.html   FAQs={n}")
    assert len(set(prices.values())) == 1, "pricing answer differs between territory headers"
    print(f"pricing answer byte-identical across {len(prices)} headers")
